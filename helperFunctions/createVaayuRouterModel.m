function text = formatToolPrompt(tools)
lines = strings(numel(tools), 1);
for idx = 1:numel(tools)
    aliasText = "";
    if ~isempty(tools(idx).Aliases)
        aliasText = " Aliases: " + strjoin(tools(idx).Aliases, ", ") + ".";
    end
    inputText = schemaToText(tools(idx).InputArguments);
    outputText = schemaToText(tools(idx).OutputArguments);
    lines(idx) = "- function " + tools(idx).Name + "(params) -> result: " + ...
        tools(idx).Description + " Inputs: " + inputText + ...
        " Outputs: " + outputText + aliasText;
end
text = strjoin(lines, newline);
end

function text = schemaToText(schema)
fields = string(fieldnames(schema));
parts = strings(numel(fields), 1);
for idx = 1:numel(fields)
    parts(idx) = fields(idx) + "=" + string(schema.(fields(idx)));
end
text = strjoin(parts, "; ");
end
